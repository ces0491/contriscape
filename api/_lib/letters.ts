/** Whether the card can write a character. Text is written in capitals, so either case will do. */
export const canWrite = (character: string): boolean => character.toUpperCase() in GLYPHS;

/** How wide a line of text is, in pixels, with cells `scale` pixels across. */
export const textWidth = (text: string, scale: number): number => Math.max(0, text.length * ADVANCE - 1) * scale;

/** How tall a line of text is, in pixels. */
export const textHeight = (scale: number): number => ROWS * scale;

/**
 * Writes a line of block capitals with its top left corner at a point. `gap` leaves that many pixels dark at the right
 * and bottom of each cell, which turns a large letter into a wall of lit windows. A character with no letter is left
 * as a space.
 */
export function write(picture: Picture, text: string, x: number, y: number, scale: number, colour: Rgb, gap = 0): void {
  [...text.toUpperCase()].forEach((character, index) => {
    const glyph = GLYPHS[character];
    if (!glyph) return;
    glyph.forEach((line, row) => {
      for (let column = 0; column < COLUMNS; column++) {
        if (line[column] !== '#') continue;
        picture.rect(x + (index * ADVANCE + column) * scale, y + row * scale, scale - gap, scale - gap, colour);
      }
    });
  });
}
